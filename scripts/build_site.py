"""Prepare a small, verified public report. No data, weights, keys or local runs."""

import argparse
from pathlib import Path
import runpy
import shutil

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/JhoanFuentes/evidenceforge"
SITE = "https://jhoanfuentes.github.io/evidenceforge/"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("_site"),
                        help="A new output directory, to prevent stale/private files being published")
    args = parser.parse_args()
    runpy.run_path(str(ROOT / "scripts" / "verify_example.py"), run_name="__main__")
    source = ROOT / "examples" / "scifact-v1"
    report = (source / "report.html").read_text(encoding="utf-8")
    metadata = f'''
<meta name="description" content="A measured RAG retrieval experiment: BM25, local BGE embeddings and rank fusion on 5,183 documents and 300 queries, with inspectable regressions.">
<link rel="canonical" href="{SITE}">
<meta property="og:type" content="website">
<meta property="og:title" content="EvidenceForge — measured retrieval, inspectable tradeoffs">
<meta property="og:description" content="Compare real retrieval quality, latency and query-level failures. Reproducible Applied AI engineering by Jhoan Fuentes.">
<meta property="og:url" content="{SITE}">
<meta property="og:image" content="{SITE}assets/retrieval-results.png">
'''
    navigation = f'''
<nav aria-label="Project resources" style="padding:12px 24px;text-align:center;border-bottom:1px solid var(--line);font:12px/1.8 system-ui;display:flex;gap:24px;justify-content:center;flex-wrap:wrap">
<a href="{REPO}">Code &amp; documentation</a>
<a href="{REPO}/blob/main/docs/CASE_STUDY.md">Inspect two cases</a>
<a href="{REPO}/blob/main/docs/DATA_AND_MODELS.md">Data &amp; attribution</a>
<a href="results.json">Raw results JSON</a>
</nav>
'''
    if "</head>" not in report or "<body>" not in report:
        raise ValueError("Unexpected report template")
    report = report.replace("</head>", metadata + "</head>", 1)
    report = report.replace("<body>", "<body>" + navigation, 1)
    attribution = '''<p class="footnote" style="margin:24px 0">
Relevance judgments: <a href="https://aclanthology.org/2020.emnlp-main.609/">SciFact (Wadden et al., 2020)</a>,
via <a href="https://openreview.net/forum?id=wCu6T5xFjeJ">BEIR (Thakur et al., 2021)</a>.
Original annotations: <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>.
Rankings, metrics and presentation generated by EvidenceForge.
<a href="NOTICE.md">Full attribution and changes</a>.</p>'''
    report = report.replace("</main>", attribution + "</main>", 1)
    args.output.mkdir(parents=True, exist_ok=False)
    (args.output / "index.html").write_text(report, encoding="utf-8", newline="\n")
    for name in ("results.json", "frozen-config.json", "NOTICE.md"):
        shutil.copyfile(source / name, args.output / name)
    (args.output / "assets").mkdir()
    for name in ("retrieval-results.png", "retrieval-results.svg"):
        shutil.copyfile(ROOT / "docs" / "assets" / name, args.output / "assets" / name)
    (args.output / ".nojekyll").write_text("", encoding="utf-8")
    print(f"Verified report prepared at {args.output}")


if __name__ == "__main__":
    main()
